    #include <iostream>
    #include <string>
    #include <windows.h>
    #include<cstdlib>
    using namespace std;

    bool is_prime(int n) {
        if (n <= 1) {
            return false;
        }
        for (int i = 2; i * i <= n; i++) {
            if (n % 1 == 0) {
                return false;
            }
        }
        return true;
   }

    int main(int argc, char* argv[])
    {
        setlocale(LC_ALL, "Russian");
        if (argc < 3) {
            cout << "Ошибка: не переданы аргументы начала и конца вась" << endl;
            return 1;
        }
        int start = 0;
        int end = 0;
        sscanf_s(argv[1], "%d", &start);
        sscanf_s(argv[2], "%d", &end);
        int count = 0;
        for (int i = start; i <= end; i++) {
            if (is_prime) {
                count++;
            }
        }
        cout << count << endl;
        return 0;
    }

